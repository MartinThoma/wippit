#!/usr/bin/env python3
"""Generate Wippit!'s build artefacts. Python 3 standard library only.

Generated files (all committed, so GitHub Pages can serve the repo as-is):

  icons/icon-192.png, icons/icon-512.png, icons/maskable-512.png,
  icons/apple-touch-icon.png   -- app icons, rendered from vector shapes below
  version.js                   -- window.WIPPIT_VERSION, a content hash of all sources
  sw.js                        -- service worker with the precache list for that version

The version changes whenever any source file changes, which makes browsers that
have the game installed download and activate the new version automatically.

Usage:
  build.py          write the files
  build.py --check  exit 1 if any generated file is missing or out of date
"""
import argparse
import hashlib
import json
import math
import struct
import sys
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Hand-written files that make up the app (and are precached by the service worker).
SOURCES = [
    "index.html",
    "style.css",
    "manifest.webmanifest",
    "js/main.js",
    "js/game.js",
    "js/render.js",
    "js/audio.js",
    "js/pwa.js",
    "icons/favicon.svg",
]

ICONS = {
    "icons/icon-512.png": (512, False),
    "icons/icon-192.png": (192, False),
    "icons/apple-touch-icon.png": (180, False),
    "icons/maskable-512.png": (512, True),
}

SW_TEMPLATE = r"""/* Generated by tools/build.py — do not edit by hand. */
const VERSION = '__VERSION__';
const CACHE = `wippit-${VERSION}`;
const ASSETS = __ASSETS__;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Bypass the HTTP cache so a new version always gets fresh files.
    await cache.addAll(ASSETS.map((url) => new Request(url, { cache: 'reload' })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys
      .filter((key) => key.startsWith('wippit-') && key !== CACHE)
      .map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (req.mode === 'navigate') {
      const page = await cache.match('./index.html');
      if (page) return page;
    }
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      return await fetch(req);
    } catch (err) {
      return new Response('Offline', { status: 503, headers: { 'Content-Type': 'text/plain' } });
    }
  })());
});
"""


# ---------------------------------------------------------------------------
# Tiny software rasteriser for the icons
# ---------------------------------------------------------------------------

def clamp01(x):
    return 0.0 if x < 0 else 1.0 if x > 1 else x


def smooth(e0, e1, x):
    t = clamp01((x - e0) / (e1 - e0))
    return t * t * (3 - 2 * t)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


class Canvas:
    def __init__(self, size):
        self.size = size
        self.px = [0.0] * (size * size * 4)  # straight (non-premultiplied) RGBA, 0..255 / 0..1

    def blend(self, x, y, rgb, a):
        if a <= 0:
            return
        i = (y * self.size + x) * 4
        p = self.px
        da = p[i + 3]
        oa = a + da * (1 - a)
        if oa <= 0:
            return
        for k in range(3):
            p[i + k] = (rgb[k] * a + p[i + k] * da * (1 - a)) / oa
        p[i + 3] = oa

    def rows(self):
        s = self.size
        for y in range(s):
            row = bytearray()
            base = y * s * 4
            for x in range(s):
                i = base + x * 4
                row += bytes((
                    int(round(min(255, max(0, self.px[i])))),
                    int(round(min(255, max(0, self.px[i + 1])))),
                    int(round(min(255, max(0, self.px[i + 2])))),
                    int(round(min(255, max(0, self.px[i + 3] * 255)))),
                ))
            yield bytes(row)


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def fill_background(cv, rounded):
    s = cv.size
    radius = 0.22 * s
    c0, c1 = hex_rgb("#5a2ca0"), hex_rgb("#0e6b7c")
    for y in range(s):
        for x in range(s):
            px, py = x + 0.5, y + 0.5
            a = 1.0
            if rounded:
                # signed distance to a rounded square
                qx = abs(px - s / 2) - (s / 2 - radius)
                qy = abs(py - s / 2) - (s / 2 - radius)
                d = math.hypot(max(qx, 0), max(qy, 0)) + min(max(qx, qy), 0) - radius
                a = 1 - smooth(-1.0, 1.0, d)
                if a <= 0:
                    continue
            t = clamp01((px + py) / (2 * s))
            col = mix(c0, c1, t)
            # soft light from the top left
            glow = 0.18 * (1 - clamp01(math.hypot(px - 0.25 * s, py - 0.2 * s) / (0.9 * s)))
            col = mix(col, (255, 255, 255), glow)
            cv.blend(x, y, col, a)


def shadow(cv, cx, cy, r, alpha):
    s = cv.size
    for y in range(max(0, int(cy - r - 2)), min(s, int(cy + r + 3))):
        for x in range(max(0, int(cx - r - 2)), min(s, int(cx + r + 3))):
            d = math.hypot(x + 0.5 - cx, y + 0.5 - cy)
            a = alpha * (1 - smooth(r * 0.55, r, d))
            cv.blend(x, y, (0, 0, 0), a)


def ball(cv, cx, cy, r, base):
    s = cv.size
    base = hex_rgb(base)
    light = mix(base, (255, 255, 255), 0.75)
    dark = mix(base, (0, 0, 0), 0.6)
    hx, hy = cx - 0.35 * r, cy - 0.4 * r
    sx, sy = cx - 0.38 * r, cy - 0.45 * r
    shadow(cv, cx + 0.08 * r, cy + 0.14 * r, r * 1.05, 0.4)
    for y in range(max(0, int(cy - r - 2)), min(s, int(cy + r + 3))):
        for x in range(max(0, int(cx - r - 2)), min(s, int(cx + r + 3))):
            px, py = x + 0.5, y + 0.5
            d = math.hypot(px - cx, py - cy)
            a = 1 - smooth(r - 1.0, r + 1.0, d)
            if a <= 0:
                continue
            t = min(1.0, math.hypot(px - hx, py - hy) / (1.25 * r))
            if t < 0.35:
                col = mix(light, base, t / 0.35)
            else:
                col = mix(base, dark, (t - 0.35) / 0.65)
            ds = ((px - sx) / (0.3 * r)) ** 2 + ((py - sy) / (0.17 * r)) ** 2
            col = mix(col, (255, 255, 255), 0.85 * (1 - smooth(0.6, 1.2, ds)))
            col = mix(col, (0, 0, 0), 0.35 * smooth(0.9 * r, r, d))
            cv.blend(x, y, col, a)


def plank(cv, cx, cy, half_len, half_th, angle):
    s = cv.size
    dx, dy = math.cos(angle), math.sin(angle)
    light, dark = hex_rgb("#f0c27a"), hex_rgb("#7a4a1c")
    reach = half_len + half_th + 2
    for y in range(max(0, int(cy - reach)), min(s, int(cy + reach) + 1)):
        for x in range(max(0, int(cx - reach)), min(s, int(cx + reach) + 1)):
            px, py = x + 0.5 - cx, y + 0.5 - cy
            u = px * dx + py * dy
            v = -px * dy + py * dx
            # rounded ends
            qu = abs(u) - (half_len - half_th)
            d = math.hypot(max(qu, 0), v) - half_th if qu > 0 else abs(v) - half_th
            a = 1 - smooth(-1.0, 1.0, d)
            if a <= 0:
                continue
            col = mix(light, dark, clamp01((v + half_th) / (2 * half_th)))
            cv.blend(x, y, col, a)


def triangle(cv, ax, ay, half_w, h):
    """Pivot: apex at (ax, ay), base h below with the given half width."""
    s = cv.size
    col = hex_rgb("#3b2a4a")
    # edge normals (outward) of the two slanted sides
    n = math.hypot(h, half_w)
    for y in range(max(0, int(ay - 2)), min(s, int(ay + h + 3))):
        for x in range(max(0, int(ax - half_w - 2)), min(s, int(ax + half_w + 3))):
            px, py = x + 0.5 - ax, y + 0.5 - ay
            d_left = (-px * h - py * half_w) / n      # outside if > 0
            d_right = (px * h - py * half_w) / n
            d_bottom = py - h
            d = max(d_left, d_right, d_bottom)
            a = 1 - smooth(-1.0, 1.0, d)
            cv.blend(x, y, col, a)


def render_icon(size, maskable):
    cv = Canvas(size)
    fill_background(cv, rounded=not maskable)
    # Maskable icons get cropped to a circle by some launchers: keep content in the safe zone.
    k = 0.78 if maskable else 1.0
    def P(fx, fy):
        return (size / 2 + (fx - 0.5) * size * k, size / 2 + (fy - 0.5) * size * k)
    angle = -0.3
    pivot = P(0.5, 0.66)
    triangle(cv, pivot[0], pivot[1], 0.11 * size * k, 0.2 * size * k)
    plank(cv, pivot[0], pivot[1], 0.38 * size * k, 0.038 * size * k, angle)
    dx, dy = math.cos(angle), math.sin(angle)
    nx, ny = math.sin(angle), -math.cos(angle)  # "up" relative to the plank
    th = 0.038 * size * k
    # heavy red ball sitting on the low (left) end
    r1 = 0.15 * size * k
    u1 = -0.27 * size * k
    ball(cv, pivot[0] + u1 * dx + nx * (th + r1), pivot[1] + u1 * dy + ny * (th + r1), r1, "#ff4d5e")
    # light blue ball being launched from the high (right) end
    r2 = 0.11 * size * k
    u2 = 0.27 * size * k
    lift = 0.1 * size * k
    ball(cv, pivot[0] + u2 * dx + nx * (th + r2 + lift), pivot[1] + u2 * dy + ny * (th + r2 + lift), r2, "#3a86ff")
    # small yellow ball flying high
    r3 = 0.075 * size * k
    c3 = P(0.6, 0.17)
    ball(cv, c3[0], c3[1], r3, "#ffd23f")
    return cv


def encode_png(cv):
    raw = b"".join(b"\x00" + row for row in cv.rows())

    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", cv.size, cv.size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw, 9))
            + chunk(b"IEND", b""))


# ---------------------------------------------------------------------------
# Version, service worker, output
# ---------------------------------------------------------------------------

def compute_version():
    h = hashlib.sha256()
    for rel in SOURCES + ["tools/build.py"]:
        h.update(rel.encode())
        h.update(b"\0")
        h.update((ROOT / rel).read_bytes())
        h.update(b"\0")
    return h.hexdigest()[:12]


def build_outputs():
    version = compute_version()
    outputs = {}
    for rel, (size, maskable) in ICONS.items():
        outputs[rel] = encode_png(render_icon(size, maskable))
    outputs["version.js"] = f'window.WIPPIT_VERSION = "{version}";\n'.encode()
    assets = ["./", "./version.js"] + [f"./{p}" for p in SOURCES] + [f"./{p}" for p in ICONS]
    sw = SW_TEMPLATE.replace("__VERSION__", version).replace("__ASSETS__", json.dumps(assets, indent=2))
    outputs["sw.js"] = sw.encode()
    return version, outputs


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = ap.parse_args()

    missing = [rel for rel in SOURCES if not (ROOT / rel).exists()]
    if missing:
        sys.exit(f"missing source files: {', '.join(missing)}")

    version, outputs = build_outputs()
    stale = []
    for rel, data in outputs.items():
        path = ROOT / rel
        if not path.exists() or path.read_bytes() != data:
            stale.append(rel)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    if args.check:
        if stale:
            print(f"out of date (run `make build`): {', '.join(stale)}")
            sys.exit(1)
        print(f"up to date, version {version}")
    else:
        print(f"built version {version}; wrote {len(stale)} file(s)" if stale else f"version {version}, nothing to do")


if __name__ == "__main__":
    main()
